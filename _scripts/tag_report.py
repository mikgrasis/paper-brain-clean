"""Tag counts and hub proposals -> _reports/hub-report.md.

Counts references per tag, including child tags (a reference tagged
tensors/hosvd/truncated counts toward tensors/hosvd and tensors), then
proposes hubs by these thresholds:
- hub: a top-level tag whose subtree holds >= HUB references;
- sub-hub: a deeper tag holding >= SUB references whose top level is a hub;
- filing axes (AXES below: organizing tags such as by-dataset) are not
  subjects: never proposed themselves, but their children can be;
- merge candidates: tags with fewer than MERGE references.
Existing hubs (topics/*.md `covers:`) are marked. Nothing is created; hubs are
made only on approval. Tune the thresholds here if hubs pile up.

    python3 _scripts/tag_report.py
"""
import glob
import re
from collections import Counter, defaultdict
from datetime import date
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
HUB, SUB, MERGE = 25, 15, 3
AXES = set()        # organizing tags that are never subjects, e.g. {"by-dataset", "by-method"}
DECLINED = set()    # proposals you declined: still listed, marked instead of proposed again


def frontmatter(path):
    m = re.match(r"---\n(.*?)\n---\n", Path(path).read_text(encoding="utf-8"), re.S)
    return (yaml.safe_load(m.group(1)) or {}) if m else {}


def main():
    refs = [frontmatter(p) for p in glob.glob(str(ROOT / "references" / "*.md"))]
    covered = set()
    for p in glob.glob(str(ROOT / "topics" / "*.md")):
        covered |= set(frontmatter(p).get("covers") or [])

    subtree = defaultdict(set)
    direct = Counter()
    for r in refs:
        for t in r.get("tags") or []:
            direct[t] += 1
            parts = t.split("/")
            for i in range(1, len(parts) + 1):
                subtree["/".join(parts[:i])].add(r["bibkey"])
    n = {t: len(v) for t, v in subtree.items()}
    axis = lambda t: t.split("/")[-1] in AXES
    hubs = sorted((t for t in n if n[t] >= HUB and "/" not in t and not axis(t)), key=lambda t: -n[t])
    subs = sorted((t for t in n if "/" in t and n[t] >= SUB and t.split("/")[0] in hubs and not axis(t)), key=lambda t: t)
    merges = sorted(t for t in n if n[t] < MERGE)
    untagged = sum(1 for r in refs if not r.get("tags"))

    mark = lambda t: " ✓ covered" if t in covered else (" declined" if t in DECLINED else "")
    out = [f"# Hub report — {date.today().isoformat()}", "",
           f"Generated by `_scripts/tag_report.py`. Thresholds: hub ≥ {HUB}, sub-hub ≥ {SUB} under a hub, "
           f"merge candidate < {MERGE}. Counts include child tags. Nothing here is created automatically.", "",
           f"{len(refs)} references, {len(n)} tags, {untagged} references without any tag.", "",
           "## Proposed hubs (top-level tags)", "", "| Tag | References | |", "|---|---|---|"]
    out += [f"| `{t}` | {n[t]} |{mark(t)} |" for t in hubs]
    out += ["", "## Proposed sub-hubs (deeper tags, under a hub)", "", "| Tag | References | |", "|---|---|---|"]
    out += [f"| `{t}` | {n[t]} |{mark(t)} |" for t in subs]
    out += ["", f"## Merge candidates (< {MERGE} references): {len(merges)}", "",
            ", ".join(f"`{t}` ({n[t]})" for t in merges), "",
            "## All tags", "", "| Tag | Direct | With children |", "|---|---|---|"]
    out += [f"| `{t}` | {direct[t]} | {n[t]} |" for t in sorted(n)]
    (ROOT / "_reports").mkdir(exist_ok=True)
    (ROOT / "_reports" / "hub-report.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"hubs {len(hubs)}, sub-hubs {len(subs)}, merge candidates {len(merges)}, tags {len(n)}, untagged {untagged}")


if __name__ == "__main__":
    main()
