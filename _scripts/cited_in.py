#!/usr/bin/env python3
"""Write a "Cited in" list into each reference note, from the vaults that cite this library.

    python3 _scripts/cited_in.py           # write
    python3 _scripts/cited_in.py --check   # change nothing; exit 1 if a note would change

The citing vaults are `citing_vaults` in _scripts/settings.json: paths, absolute or relative to this vault
("." includes this vault). Every Markdown note in them is scanned for [@key] citations, the numbered form
those citations take after a References build ([[#^ref-key|1]]), and keys listed in a `cites:` frontmatter
field. Each reference note gets a collapsed callout after its %% bib:end %% marker, between
%% cited-in:start %% and %% cited-in:end %%, linking every citing note (obsidian:// links to other vaults,
which open once Obsidian knows the vault). Keys cited but missing from library.bib are reported.
"""
import json
import re
import sys
from collections import defaultdict
from pathlib import Path
from urllib.parse import quote

import yaml

ROOT = Path(__file__).resolve().parent.parent
SETTINGS = json.loads((ROOT / "_scripts" / "settings.json").read_text(encoding="utf-8"))
SKIP = {".obsidian", ".git", ".trash", "_trash", "_templates", "_attachments", "node_modules"}
KEY = r"[A-Za-z0-9_][A-Za-z0-9_:.\-]*[A-Za-z0-9_]"
GROUP = re.compile(r"\[([^\[\]\n]*@" + KEY + r"[^\[\]\n]*)\]")
NUMBERED = re.compile(r"\[\[#\^ref-([A-Za-z0-9-]+)\\?\|\d+\]\]")
CODE = re.compile(r"^```.*?^```|`[^`\n]*`", re.S | re.M)
FM = re.compile(r"\A---\n(.*?)\n---\n", re.S)
BLOCK = re.compile(r"\n*%% cited-in:start[^\n]*%%\n.*?%% cited-in:end %%\n?", re.S)
BIBEND = "%% bib:end %%"


def block_id(key):
    return "ref-" + re.sub(r"[^A-Za-z0-9-]", "-", key)


def cited(text, ids):
    m = FM.match(text)
    try:
        fm = (yaml.safe_load(m.group(1)) or {}) if m else {}
    except yaml.YAMLError:
        fm = {}
    body = CODE.sub("", text[m.end():] if m else text)
    keys = [k for g in GROUP.findall(body) for k in re.findall(r"@(" + KEY + r")", g)]
    keys += [ids.get(i, i) for i in NUMBERED.findall(body)]
    keys += [str(k) for k in (fm.get("cites") or [])]
    return fm, list(dict.fromkeys(keys))


def main():
    check = "--check" in sys.argv
    keys = set(re.findall(r"^@\w+\s*\{\s*([^,\s]+)\s*,", (ROOT / "library.bib").read_text(encoding="utf-8"), re.M))
    ids = {block_id(k): k for k in keys}
    citers, missing = defaultdict(list), defaultdict(set)
    for v in SETTINGS["citing_vaults"]:
        vault = (ROOT / v).resolve()
        if not vault.is_dir():
            print(f"skipped, not found: {v}", file=sys.stderr)
            continue
        for p in sorted(vault.rglob("*.md")):
            rel = p.relative_to(vault).as_posix()
            if set(rel.split("/")[:-1]) & SKIP or (vault == ROOT and rel.startswith("references/")):
                continue
            fm, ks = cited(p.read_text(encoding="utf-8", errors="ignore"), ids)
            label = str(fm.get("title") or p.stem)
            for k in ks:
                if k in keys:
                    citers[k].append((vault, rel, label))
                else:
                    missing[k].add(f"{vault.name}/{rel}")
    changed = []
    for p in sorted((ROOT / "references").glob("*.md")):
        text = p.read_text(encoding="utf-8")
        base = BLOCK.sub("\n", text)
        new = base
        if p.stem in citers and BIBEND in base:
            entries = sorted(set(citers[p.stem]), key=lambda c: (c[0].name, c[1]))
            lines = ["%% cited-in:start: generated by _scripts/cited_in.py, do not edit %%",
                     f"> [!quote]- Cited in {len(entries)} note{'s' if len(entries) != 1 else ''}"]
            for vault, rel, label in entries:
                target = rel[:-3]
                link = f"[[{target}|{label}]]" if vault == ROOT else \
                    f"[{label}](obsidian://open?vault={quote(vault.name)}&file={quote(target, safe='')}) · {vault.name}"
                lines.append(f"> - {link}")
            lines.append("%% cited-in:end %%")
            new = re.sub(r"(%% bib:end %%)\n\n+", r"\1\n\n", base).replace(BIBEND + "\n", BIBEND + "\n\n" + "\n".join(lines) + "\n", 1)
        if new != text:
            changed.append(p.name)
            if not check:
                p.write_text(new, encoding="utf-8", newline="\n")
    for name in changed:
        print(("would change " if check else "updated ") + "references/" + name)
    for k in sorted(missing):
        print(f"not in library.bib: {k} ({', '.join(sorted(missing[k]))})", file=sys.stderr)
    sys.exit(1 if check and changed else 0)


if __name__ == "__main__":
    main()
